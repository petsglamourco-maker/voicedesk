import { llm, voice } from "@livekit/agents";
import { holdOnPhrase } from "@voicedesk/agent-brain";
import type { EngineBridge, TurnTimings } from "./bridge";

/**
 * AgentSession only runs the speech pipeline when it has an LLM, but every reply here
 * comes from the VoiceDesk engine through EngineVoiceAgent.llmNode, so this is never called.
 */
export class EngineLlmPlaceholder extends llm.LLM {
  label(): string {
    return "voicedesk.engine";
  }

  chat(): llm.LLMStream {
    throw new Error("Replies come from the VoiceDesk engine (EngineVoiceAgent.llmNode)");
  }
}

/** What the caller said since the agent last spoke (several fragments are joined). */
export function newCallerText(chatCtx: llm.ChatContext): string {
  const parts: string[] = [];
  for (let i = chatCtx.items.length - 1; i >= 0; i--) {
    const item = chatCtx.items[i]!;
    if (item.type !== "message") continue;
    if (item.role === "assistant") break;
    const text = item.role === "user" ? item.textContent?.trim() : undefined;
    if (text) parts.unshift(text);
  }
  return parts.join(" ");
}

export interface TimingHooks {
  /** LiveKit end-of-utterance metrics for the turn being answered. */
  pending: () => TurnTimings;
  /** Called when the first text is out and again when the turn is saved. */
  report: (timings: TurnTimings) => void;
}

/**
 * After this long without reply text, say a short hold-on phrase (lookups take 2–5 s). An
 * ordinary answer usually starts within 2 s, so it doesn't get one (the 2026-10-20 phone
 * test on 1 s said "Just a moment" on 12 of 14 turns).
 */
export const FILLER_AFTER_MS = 2000;
/** Right after a turn that needed one, wait longer: back-to-back fillers sound robotic. */
export const REPEAT_FILLER_AFTER_MS = 3500;

/**
 * Turns one caller utterance into a text stream for TTS by running a full engine turn.
 * Separate from the LiveKit class so it can be tested without a room.
 */
export function engineReplyStream(
  bridge: EngineBridge,
  callerText: string,
  hooks: TimingHooks,
  fillerAfterMs?: number,
): ReadableStream<string> {
  const fillerDelay =
    fillerAfterMs ?? (bridge.lastTurnHadFiller ? REPEAT_FILLER_AFTER_MS : FILLER_AFTER_MS);
  const startedAt = Date.now();
  const timings: TurnTimings = { ...hooks.pending() };
  let open = true;
  const firstText = () => {
    if (timings.llmFirstTextMs !== undefined) return;
    timings.llmFirstTextMs = Date.now() - startedAt;
    hooks.report(timings);
  };
  return new ReadableStream<string>({
    start: (controller) => {
      const filler = setTimeout(() => {
        if (!open || timings.llmFirstTextMs !== undefined) return;
        timings.filler = true;
        firstText();
        controller.enqueue(`${holdOnPhrase(bridge.language, bridge.fillersSpoken++)} `);
      }, fillerDelay);
      void bridge
        .handleTurn(
          callerText,
          (delta) => {
            clearTimeout(filler);
            firstText();
            // After a barge-in LiveKit cancels the stream; the turn still completes and is
            // saved, so a booking the caller already confirmed is not lost.
            if (open) controller.enqueue(delta);
          },
          () => ({ latency: { ...timings, engineMs: Date.now() - startedAt } }),
        )
        .then((result) => {
          timings.engineMs = result?.latencyMs ?? Date.now() - startedAt;
          hooks.report(timings);
        })
        .finally(() => {
          clearTimeout(filler);
          bridge.lastTurnHadFiller = timings.filler === true;
          if (open) controller.close();
          open = false;
        });
    },
    cancel: () => {
      open = false;
    },
  });
}

/**
 * Voice agent whose "LLM step" is a full engine turn: flows, tools, records and the AI
 * provider router are exactly those of the text console (ADR 0013). Text before a tool call
 * (e.g. "Let me check that for you") streams straight to TTS, so the caller hears it at once.
 */
export class EngineVoiceAgent extends voice.Agent {
  constructor(
    private readonly bridge: EngineBridge,
    private readonly hooks: TimingHooks,
  ) {
    super({ instructions: "Replies are generated by the VoiceDesk conversation engine." });
  }

  override async llmNode(
    chatCtx: llm.ChatContext,
    _toolCtx: llm.ToolContext,
    _modelSettings: voice.ModelSettings,
  ): Promise<ReadableStream<string> | null> {
    const callerText = newCallerText(chatCtx);
    if (!callerText) return null;
    // With a person (or ringing for one): keep the transcript, don't answer.
    if (this.bridge.humanActive) {
      void this.bridge.saveCallerSpeech(callerText);
      return null;
    }
    return engineReplyStream(this.bridge, callerText, this.hooks);
  }
}
