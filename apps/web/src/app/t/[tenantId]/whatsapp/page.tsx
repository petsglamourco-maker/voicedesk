import { Card, CardDescription, CardTitle } from "@voicedesk/ui";
import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { getTranslations } from "next-intl/server";
import { apiGetOrNull } from "@/lib/api";
import { ScreenHero } from "@/components/screen-hero";

export const metadata: Metadata = { title: "WhatsApp" };

type WhatsAppInfo =
  { connected: false } | { connected: true; displayNumber: string; link: string; qrSvg: string };

export default async function WhatsAppPage(props: { params: Promise<{ tenantId: string }> }) {
  const { tenantId } = await props.params;
  const info = await apiGetOrNull<WhatsAppInfo>(`/api/tenants/${tenantId}/whatsapp`);
  if (!info) notFound();
  const t = await getTranslations("whatsapp");
  const shell = await getTranslations("shell");
  return (
    <div className="stagger space-y-6">
      <ScreenHero
        icon="whatsapp"
        eyebrow={shell("groups.channels")}
        title={t("title")}
        description={t("subtitle")}
      />
      {!info.connected ? (
        <Card>
          <CardTitle>{t("notConnected")}</CardTitle>
          <CardDescription>{t("notConnectedHint")}</CardDescription>
        </Card>
      ) : (
        <div className="grid gap-6 md:grid-cols-[1fr_280px]">
          <Card>
            <CardTitle>{t("yourNumber")}</CardTitle>
            <p className="mt-2 font-mono text-lg" data-testid="whatsapp-number">
              {info.displayNumber}
            </p>
            <p className="mt-4 text-sm font-medium">{t("link")}</p>
            <a
              href={info.link}
              className="text-sm text-primary hover:underline"
              target="_blank"
              rel="noreferrer"
            >
              {info.link}
            </a>
            <p className="mt-4 text-sm text-muted-foreground">{t("linkHint")}</p>
            <p className="mt-4 text-xs text-muted-foreground">{t("windowNote")}</p>
          </Card>
          <Card className="flex flex-col items-center">
            <p className="text-sm font-medium">{t("qr")}</p>
            {/* QR code SVG generated by our API from the business's own number. */}
            <div
              className="mt-3 w-60 rounded bg-white p-2"
              dangerouslySetInnerHTML={{ __html: info.qrSvg }}
              data-testid="whatsapp-qr"
            />
            <p className="mt-3 text-center text-xs text-muted-foreground">{t("qrHint")}</p>
          </Card>
        </div>
      )}
    </div>
  );
}
