import { Card, CardHead, EmptyState } from "@voicedesk/ui";
import { Clock, ExternalLink, Link2, MessageCircleOff, QrCode } from "lucide-react";
import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { getTranslations } from "next-intl/server";
import { apiGetOrNull } from "@/lib/api";
import { ScreenHero } from "@/components/screen-hero";
import { WhatsAppIcon } from "@/components/shell/icons";

export const metadata: Metadata = { title: "WhatsApp" };

type WhatsAppInfo =
  { connected: false } | { connected: true; displayNumber: string; link: string; qrSvg: string };

const WA = "var(--color-ch-whatsapp)";

export default async function WhatsAppPage(props: { params: Promise<{ tenantId: string }> }) {
  const { tenantId } = await props.params;
  const info = await apiGetOrNull<WhatsAppInfo>(`/api/tenants/${tenantId}/whatsapp`);
  if (!info) notFound();
  const t = await getTranslations("whatsapp");
  const shell = await getTranslations("shell");
  return (
    <div className="stagger space-y-6">
      <ScreenHero
        icon="whatsapp"
        eyebrow={shell("groups.channels")}
        title={t("title")}
        description={t("subtitle")}
      />
      {!info.connected ? (
        <Card variant="ghost">
          <EmptyState
            icon={MessageCircleOff}
            title={t("notConnected")}
            description={t("notConnectedHint")}
          />
        </Card>
      ) : (
        <div className="grid gap-6 md:grid-cols-[1fr_300px] [&>*]:min-w-0">
          <Card
            className="relative overflow-hidden"
            style={{
              borderColor: `color-mix(in srgb, ${WA} 35%, transparent)`,
              boxShadow: `0 0 40px -16px ${WA}`,
            }}
          >
            <div
              aria-hidden
              className="pointer-events-none absolute -end-16 -top-16 size-56 rounded-full blur-3xl"
              style={{ background: `color-mix(in srgb, ${WA} 22%, transparent)` }}
            />
            <div className="relative">
              <CardHead icon={<WhatsAppIcon />} title={t("yourNumber")} color={WA} />
              <p
                className="tabular mt-4 font-display text-3xl font-semibold tracking-tight"
                data-testid="whatsapp-number"
                dir="ltr"
              >
                {info.displayNumber}
              </p>

              <div className="mt-6 border-t border-border pt-5">
                <CardHead
                  as="h3"
                  icon={<Link2 />}
                  title={t("link")}
                  hint={t("linkHint")}
                  color={WA}
                />
                <a
                  href={info.link}
                  className="glass mt-3 flex max-w-full items-center gap-2 rounded-lg px-3 py-2 font-mono text-sm break-all text-secondary transition-colors hover:border-input hover:underline"
                  target="_blank"
                  rel="noreferrer"
                  dir="ltr"
                >
                  <span className="min-w-0 flex-1">{info.link}</span>
                  <ExternalLink aria-hidden className="size-4 shrink-0" style={{ color: WA }} />
                </a>
              </div>

              <p className="mt-6 flex items-start gap-2 rounded-lg border border-border bg-[color-mix(in_srgb,var(--color-surface)_55%,transparent)] px-3 py-2.5 text-xs text-muted-foreground">
                <Clock aria-hidden className="mt-0.5 size-3.5 shrink-0" style={{ color: WA }} />
                <span>{t("windowNote")}</span>
              </p>
            </div>
          </Card>
          <Card className="flex flex-col items-center text-center">
            <CardHead icon={<QrCode />} title={t("qr")} color={WA} className="self-stretch" />
            <div className="relative mt-5">
              <div
                aria-hidden
                className="pointer-events-none absolute -inset-3 rounded-3xl opacity-70 blur-xl"
                style={{ background: `color-mix(in srgb, ${WA} 35%, transparent)` }}
              />
              {/* QR code SVG generated by our API from the business's own number, shown as an
                  image (never injected as HTML). White stays white (needed for scanning). */}
              <div className="relative w-56 rounded-xl bg-white p-3 shadow-lg">
                <img
                  src={`data:image/svg+xml;base64,${Buffer.from(info.qrSvg).toString("base64")}`}
                  alt={t("qrAlt")}
                  className="block h-auto w-full"
                  data-testid="whatsapp-qr"
                />
              </div>
            </div>
            <p className="mt-5 text-xs text-muted-foreground">{t("qrHint")}</p>
          </Card>
        </div>
      )}
    </div>
  );
}
